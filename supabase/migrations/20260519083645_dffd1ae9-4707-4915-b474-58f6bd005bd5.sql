  strict_rules,
  '📞 เรื่องการโทร/ติดต่อกลับ — ห้ามถามลูกค้าว่า "ให้โทรหาเลยไหม / โทรตอนนี้ได้ไหม / ยืนยันให้โทรเลยไหม" และห้ามรับปากเวลาเฉพาะเจาะจง (เช่น "พรุ่งนี้ 9 โมง จะมีเจ้าหน้าที่โทร") เพราะ AI ไม่ได้เป็นแอดมินจริง อาจไม่มีคนรับสายตามเวลา | ให้พูดแบบ passive เท่านั้น เช่น "เดี๋ยวเจ้าหน้าที่ติดต่อกลับโดยเร็วที่สุดนะคะ" / "แจ้งทีมประสานให้แล้วค่ะ เจ้าหน้าที่จะติดต่อกลับในเวลาทำการ" | ถ้าลูกค้าระบุเวลาที่อยากให้โทร → ตอบ "รับทราบค่ะ จะแจ้งทีมให้ติดต่อในช่วงเวลานั้นนะคะ" (ไม่การันตี)'
)
WHERE key = 'ai_config'
AND NOT (strict_rules::text LIKE '%เรื่องการโทร/ติดต่อกลับ%');