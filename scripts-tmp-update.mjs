if (kbErr) { console.error("KB insert error:", kbErr); process.exit(1); }
console.log("✅ Inserted KB:", kb.id);

// 2) Update strict_rules
const { data: app, error: appErr } = await sb
  .from("app_settings")
  .select("id")
  .limit(1)
  .single();
if (appErr) { console.error(appErr); process.exit(1); }

const { error: updErr } = await sb
  .from("app_settings")
  .update({ strict_rules: newRules })
  .eq("id", app.id);
if (updErr) { console.error("Update error:", updErr); process.exit(1); }
console.log("✅ Updated strict_rules ->", newRules.length, "items");

